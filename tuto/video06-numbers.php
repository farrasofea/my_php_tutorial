/*
PHP has two basic number data types:

   Integer
   - Whole numbers
   - No decimal point

   Example:
   $age = 20;
   $radius = 25;

   Float
   - Numbers with decimal points

   Example:
   $pi = 3.14;
   $price = 19.99;


Mathematical operators

   +  Addition
   -  Subtraction
   *  Multiplication
   /  Division
   ** Power

   Example:
   echo 5 + 5;
   echo 5 - 2;
   echo 5 * 2;
   echo 10 / 2;
   echo 5 ** 2;


Order of operations
- PHP follows the normal mathematical order of operations:

   B - Brackets
   I - Indices
   D - Division
   M - Multiplication
   A - Addition
   S - Subtraction


Increment operator (++)
- Adds 1 to a variable.

   Example:
   $age = 20;
   $age++;

   $age becomes 21.


Decrement operator (--)
- Subtracts 1 from a variable.

   Example:
   $age = 20;
   $age--;

   $age becomes 19.


Shorthand operators

   +=  Add to a variable
   -=  Subtract from a variable
   *=  Multiply a variable
   /=  Divide a variable

   Example:
   $age = 20;
   $age += 10;

   This is the same as:
   $age = $age + 10;


Number functions

   floor()
   - Rounds down to the nearest integer.

   Example:
   floor(3.14);
   Output: 3


   ceil()
   - Rounds up to the nearest integer.

   Example:
   ceil(3.14);
   Output: 4


   pi()
   - Returns the value of pi.

   Example:
   echo pi();


IMPORTANT:

Integer = whole number
Float = decimal number

+  = addition
-  = subtraction
*  = multiplication
/  = division
** = power

++ = increase by 1
-- = decrease by 1

+= = add and assign
-= = subtract and assign
*= = multiply and assign
/= = divide and assign

floor() = round down
ceil() = round up
pi() = get pi value
*/

