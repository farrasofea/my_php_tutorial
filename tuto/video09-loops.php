<?php
/*
Arrays store multiple values inside one variable.

Types of arrays:
1. Indexed arrays
2. Associative arrays
3. Multidimensional arrays

Indexed Array:
$people = ["Shan", "Crystal", "Rayu"];

Access:
$people[1];

Associative Array:
$ninjas = [
    "Mario" => "Orange",
    "Luigi" => "Brown"
];

Access:
$ninjas["Mario"];

Multidimensional Array:
$blogs = [
    [
        "title" => "Mario Party",
        "author" => "Mario"
    ]
];

Access:
$blogs[0]["author"];

Useful array functions:
print_r()       -> displays an array in readable format
count()         -> counts elements
array_push()    -> adds an element to the end
array_pop()     -> removes the last element
array_merge()   -> combines arrays


LOOPS
- Loops repeat a block of code.

FOR LOOP:
Used when we have a condition/counter.

FOREACH LOOP:
Used to go through each item in an array.

WHILE LOOP:
Runs while a condition is true.

Important:
- Always make sure a while loop eventually becomes false to avoid an infinite loop.
- Loops can also be used inside HTML to generate repeated HTML elements from array data.
*/
